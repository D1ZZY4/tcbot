"""Domain primitive NewTypes for the TCF Bot database layer."""

from __future__ import annotations

import secrets
from typing import NewType

# * Alphabet for the generated short identifiers. Lowercase alphanumerics
# * only, so an identifier is safe to embed in a URL or a caption.
_ID_ALPHABET: str = "abcdefghijklmnopqrstuvwxyz0123456789"

# ────────────────────────── ID Primitives ───────────────────────── #
# * Distinct names prevent accidentally swapping e.g. chat_id for user_id
# * All are backed by int or str at runtime (zero overhead)

UserId = NewType("UserId", int)
"""Telegram user ID (positive integer)."""

GroupId = NewType("GroupId", int)
"""Telegram supergroup/group chat ID (typically negative integer)."""

ChatId = NewType("ChatId", int)
"""Generic Telegram chat ID; use GroupId when the chat is known to be a group."""

BanId = NewType("BanId", str)
"""Short alphanumeric federation ban identifier, generated by make_short_id()."""


def make_short_id(length: int = 10) -> str:
    """Generate a random URL-safe lowercase alphanumeric ID.

    Used for the federation ban identifier and the promotion request
    identifier. The value is derived from ``secrets``, so it is not
    predictable by an observer.
    """
    return "".join(secrets.choice(_ID_ALPHABET) for _ in range(length))
