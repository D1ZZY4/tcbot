CREATE OR REPLACE FUNCTION public.prepare_moderation_action()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  v_previous public.moderation_actions%ROWTYPE;
BEGIN
  IF (
       NEW.action_type IN ('ban', 'mute')
       AND NEW.status <> 'active'
     )
     OR (
       NEW.action_type IN ('warn', 'kick')
       AND NEW.status <> 'completed'
     )
     OR NEW.revoked_at IS NOT NULL
     OR NEW.revoked_by_user_id IS NOT NULL
     OR (
       NEW.action_type IN ('ban', 'mute')
       AND NEW.expires_at IS NOT NULL
       AND NEW.expires_at <= now()
     ) THEN
    RAISE EXCEPTION
      'New moderation actions must start in their initial status, have a future expiry, and have no revocation metadata';
  END IF;

  -- Expired rows must leave the partial unique indexes before a replacement is inserted.
  UPDATE public.moderation_actions AS a
     SET status = 'expired'
   WHERE a.federation_id = NEW.federation_id
     AND a.chat_id IS NOT DISTINCT FROM NEW.chat_id
     AND a.target_user_id = NEW.target_user_id
     AND a.action_type = NEW.action_type
     AND a.status = 'active'
     AND a.expires_at IS NOT NULL
     AND a.expires_at <= NEW.created_at;

  IF NEW.supersedes_action_id IS NOT NULL THEN
    IF NEW.action_type NOT IN ('ban', 'mute') OR NEW.status <> 'active' THEN
      RAISE EXCEPTION 'Only a new active ban or mute can supersede a previous active action';
    END IF;

    SELECT *
      INTO v_previous
      FROM public.moderation_actions AS a
      WHERE a.id = NEW.supersedes_action_id
      FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Action % selected for supersession does not exist',
        NEW.supersedes_action_id;
    END IF;

    IF v_previous.status <> 'active'
       OR v_previous.action_type <> NEW.action_type
       OR v_previous.federation_id <> NEW.federation_id
       OR v_previous.target_user_id <> NEW.target_user_id
       OR v_previous.chat_id IS DISTINCT FROM NEW.chat_id THEN
      RAISE EXCEPTION
        'Only the current active action for the same federation, chat scope, user, and action type can be superseded';
    END IF;

    UPDATE public.moderation_actions
       SET status = 'superseded'
     WHERE id = v_previous.id;
  END IF;

  RETURN NEW;
END;
$function$


